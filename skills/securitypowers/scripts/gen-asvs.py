#!/usr/bin/env python3
"""Render the official OWASP ASVS 5.0 CSV export as one Markdown table per chapter.

Usage: gen-asvs.py <OWASP_Application_Security_Verification_Standard_5.0.0_en.csv> <out.md>
Source: https://github.com/OWASP/ASVS/releases (asset *_en.csv), CC BY-SA 4.0.
"""
import csv
import sys
from collections import Counter
from pathlib import Path

HEADER = """# OWASP ASVS 5.0.0 — requirement grid

Generated by `scripts/gen-asvs.py` from the official CSV export of
[OWASP/ASVS](https://github.com/OWASP/ASVS/releases) (CC BY-SA 4.0, © OWASP Foundation).
Do not edit by hand: re-run the script on a new export.

This grid is for traceability and prioritisation, not a claim of coverage. A review marks each
requirement in scope as `verified`, `failed`, `not applicable` or `not evaluated`. A level `?`
means the export gave no level.

Requirements: {total} (L1: {l1}, L2: {l2}, L3: {l3}, unknown: {unknown})
"""


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render(rows: list[dict[str, str]]) -> str:
    levels = Counter((r.get("L") or "").strip() or "?" for r in rows)
    out = [HEADER.format(total=len(rows), l1=levels["1"], l2=levels["2"], l3=levels["3"], unknown=levels["?"])]
    chapter = None
    for r in rows:
        if r["chapter_id"] != chapter:
            chapter = r["chapter_id"]
            out.append(f"\n## {chapter} {r['chapter_name']}\n\n| ID | L | Requirement |\n|---|---|---|")
        level = (r.get("L") or "").strip() or "?"
        out.append(f"| {r['req_id']} | {level} | {_cell(r['req_description'])} |")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    with open(argv[1], encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    rows.sort(key=lambda r: [int(x) for x in r["req_id"].lstrip("V").split(".")])
    Path(argv[2]).write_text(render(rows), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
